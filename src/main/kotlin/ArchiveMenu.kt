//Экран выбора архива. Возвращает управление, когда пользователь выбирает "Назад".
fun archiveMenu(
    //Список всех архивов приложения
    archives: MutableList<Archive>
) {
    //Бесконечный цикл экрана: обновляем меню при каждом возврате с дочерних экранов
    while (true) {
        //Формируем пункты: по одному на каждый архив
        val items = archives.map { archive ->
            MenuItem(archive.name) {
                //При выборе архива открываем экран заметок этого архива
                noteMenu(archive)
            }
        }.toMutableList()

        //Добавляем пункт создания нового архива
        items.add(MenuItem("Создать архив") {
            //Создаём архив с непустым именем
            val name = readNonEmpty("Введите имя архива: ", "Ошибка: имя архива не может быть пустым.")
            archives.add(Archive(name))
            println("Архив \"$name\" создан.")
        })

        //Показываем меню; если пользователь выбрал "Назад" — выходим из экрана
        val keepGoing = showMenu("=== Архивы ===", items)
        if (!keepGoing) return
    }
}